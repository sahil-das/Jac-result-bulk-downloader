def main():
    print("--- JAC Class 10 Offline PDF Generator ---")
    
    folder_path = input("Enter the path to the folder containing JSON files (e.g., json/Your_School_Name): ").strip()
    
    if not os.path.isdir(folder_path):
        print(f"❌ Error: The directory '{folder_path}' does not exist.")
        return

    # Find all json files in the directory
    search_pattern = os.path.join(folder_path, "*.json")
    json_files = glob.glob(search_pattern)
    
    if not json_files:
        print(f"❌ Error: No JSON files found inside '{folder_path}'.")
        return
        
    print(f"\n📂 Found {len(json_files)} JSON files. Loading data...")
    
    students = []
    for file_path in json_files:
        try:
            with open(file_path, "r", encoding="utf-8") as f:
                student_data = json.load(f)
                students.append(student_data)
        except Exception as e:
            print(f"⚠️ Could not read {file_path}. Error: {e}")
            
    if not students:
        print("❌ Failed to parse any valid student data. Exiting.")
        return

    # Sort students back into numerical order by roll number
    students = sorted(students, key=lambda x: int(x['roll_no']))
    
    # Extract global details from the sorted list
    school_name = students[0].get("school", "Unknown School")
    roll_code = students[0].get("roll_code", "00000")
    start_roll = students[0].get("roll_no", "0000")
    end_roll = students[-1].get("roll_no", "0000")
    
    print(f"✅ Successfully loaded {len(students)} records for {school_name} (Roll Code: {roll_code}).")

    # =================================================================
    # FINAL PDF GENERATION
    # =================================================================
    print("\n📊 Compiling Advanced Analytics & Report Layout...")
    cover = cover_page_html(school_name, roll_code, students)
    top10 = top_10_scorers_html(students)
    details = "".join([student_html(s) for s in students])

    # Clean the school name and formulate the new exact requested string
    safe_school_name = clean_filename(school_name)[:40] 
    output_filename = f"JAC_10th_Results_{roll_code}_{safe_school_name}_{start_roll}_to_{end_roll}.pdf"

    print("📝 Generating PDF... Please wait.")
    try:
        HTML(string=cover + top10 + details).write_pdf(output_filename)
        print(f"🎉 Success! PDF saved locally as: {output_filename}")
    except Exception as e:
        print(f"❌ Error generating PDF: {e}")

if __name__ == "__main__":
    main()