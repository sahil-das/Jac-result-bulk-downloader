def main():
    print("--- JAC Class 10 Automated PDF Generator (Optimized 2026 Edition) ---")
    roll_code = input("Enter Roll Code (e.g. 11240): ").strip()
    start_roll = int(input("Enter starting Roll Number: ").strip())
    
    end_roll_input = input("Enter last Roll Number (Press ENTER to Auto-Detect): ").strip()
    auto_detect = not bool(end_roll_input)
    
    students = []
    failed_rolls = []
    school_name = "Unknown School"

    print("\n🚀 Starting Automated Parallel Fetch...")
    
    MAX_THREADS = 5
    
    if not auto_detect:
        end_roll = int(end_roll_input)
        rolls_to_check = list(range(start_roll, end_roll + 1))
        
        with concurrent.futures.ThreadPoolExecutor(max_workers=MAX_THREADS) as executor:
            futures = [executor.submit(fetch_single_student, roll, roll_code) for roll in rolls_to_check]
            for future in concurrent.futures.as_completed(futures):
                result = future.result()
                if result:
                    if result.get("status") == "SUCCESS":
                        student_data = result["data"]
                        students.append(student_data)
                        if school_name == "Unknown School":
                            school_name = student_data["school"]
                        
                        # Save JSON file immediately after fetching successfully
                        save_student_json(student_data)
                        
                    elif result.get("status") == "ERROR":
                        failed_rolls.append(result["roll"])
    
    else:
        current_roll = start_roll
        batch_size = 5
        
        while True:
            rolls_to_check = list(range(current_roll, current_roll + batch_size))
            
            with concurrent.futures.ThreadPoolExecutor(max_workers=MAX_THREADS) as executor:
                futures = [executor.submit(fetch_single_student, roll, roll_code) for roll in rolls_to_check]
                
                batch_results = []
                empty_count = 0
                
                for future in concurrent.futures.as_completed(futures):
                    result = future.result()
                    if result:
                        if result.get("status") == "SUCCESS":
                            student_data = result["data"]
                            batch_results.append(student_data)
                            if school_name == "Unknown School":
                                school_name = student_data["school"]
                            
                            # Save JSON file immediately after fetching successfully
                            save_student_json(student_data)

                        elif result.get("status") == "EMPTY":
                            empty_count += 1
                        elif result.get("status") == "ERROR":
                            failed_rolls.append(result["roll"])
            
            students.extend(batch_results)
            
            if empty_count == len(rolls_to_check):
                print("\n🛑 Hit a completely empty batch. Assuming end of class detected.")
                break
                
            current_roll += batch_size

    # =================================================================
    # FAILED ROLLS RETRY
    # =================================================================
    if failed_rolls:
        print(f"\n⚠️ {len(failed_rolls)} roll numbers failed after all retries: {failed_rolls}")
        retry_choice = input("Do you want to retry these failed roll numbers now? (y/n): ").strip().lower()
        
        if retry_choice == 'y':
            print("\n🔄 Retrying failed rolls sequentially...")
            still_failed = []
            for roll in failed_rolls:
                res = fetch_single_student(roll, roll_code, max_retries=3) 
                if res and res.get("status") == "SUCCESS":
                    student_data = res["data"]
                    students.append(student_data)
                    if school_name == "Unknown School":
                        school_name = student_data["school"]
                    
                    # Save JSON file immediately
                    save_student_json(student_data)

                elif res and res.get("status") == "ERROR":
                    still_failed.append(roll)
            
            failed_rolls = still_failed
            if failed_rolls:
                print(f"❌ These rolls still failed: {failed_rolls}")
            else:
                print("✅ All failed rolls successfully recovered!")

    # =================================================================
    # MANUAL RECOVERY MODE
    # =================================================================
    print("\n" + "="*50)
    print("🛠️  MANUAL RECOVERY MODE")
    print("If any roll numbers failed or were skipped, you can fetch them now.")
    print("Press [ENTER] directly if you want to skip and generate the PDF.")
    print("="*50)
    
    while True:
        manual_input = input("\nEnter Roll Number to fetch manually (or press ENTER to finish): ").strip()
        if not manual_input:
            break
            
        if not manual_input.isdigit():
            print("⚠️ Invalid input. Please enter numbers only.")
            continue
            
        manual_roll = int(manual_input)
        print(f"Fetching Roll {str(manual_roll).zfill(4)}...")
        
        result = fetch_single_student(manual_roll, roll_code, max_retries=3)
        
        if result and result.get("status") == "SUCCESS":
            student_data = result["data"]
            formatted_new_roll = str(manual_roll).zfill(4)
            original_length = len(students)
            students = [s for s in students if s["roll_no"] != formatted_new_roll]
            
            if len(students) < original_length:
                print(f"🔄 Roll {formatted_new_roll} was already in the list. Overwriting with fresh data...")
                
            students.append(student_data)
            if school_name == "Unknown School":
                school_name = student_data["school"]
            
            # Save the manual entry JSON file too
            save_student_json(student_data)
                
            print(f"✅ Roll {formatted_new_roll} successfully added to the final report & saved to JSON folder.")
        elif result and result.get("status") == "EMPTY":
            print(f"❌ Student not found. No record exists for Roll {str(manual_roll).zfill(4)}.")
        else:
            print("⚠️ Failed to fetch. Server might be down or busy.")

    # =================================================================
    # JSON MASTER SAVE & FINAL PDF GENERATION
    # =================================================================
    if not students:
        print("\nNo student data fetched. Exiting without generating PDF.")
        return

    # Keep the master JSON backup
    master_json_filename = f"JAC_10th_{roll_code}_data_master.json"
    print(f"\n💾 Saving master list backup to {master_json_filename}...")
    with open(master_json_filename, "w", encoding="utf-8") as f:
        json.dump(students, f, indent=4, ensure_ascii=False)

    # Sort students into numerical order
    students = sorted(students, key=lambda x: int(x['roll_no']))

    print("\n📊 Compiling Advanced Analytics & Report Layout...")
    cover = cover_page_html(school_name, roll_code, students)
    top10 = top_10_scorers_html(students)
    details = "".join([student_html(s) for s in students])

    # Extract global details from the sorted list for filename
    start_roll_str = students[0].get("roll_no", "0000")
    end_roll_str = students[-1].get("roll_no", "0000")
    safe_school_name = clean_filename(school_name)[:40]
    output_filename = f"JAC_10th_Results_{roll_code}_{safe_school_name}_{start_roll_str}_to_{end_roll_str}.pdf"

    print("📝 Generating PDF... Please wait.")
    HTML(string=cover + top10 + details).write_pdf(output_filename)
    print(f"✅ Success! PDF saved as: {output_filename}")
    print(f"📁 All individual JSON files are saved inside: json/{clean_filename(school_name)}/")

if __name__ == "__main__":
    main()