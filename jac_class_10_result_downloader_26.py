# Thread lock to prevent print statements from scrambling in the terminal
print_lock = threading.Lock()

def clean_filename(name):
    """Cleans a string to be safe for OS file and folder names."""
    return re.sub(r'(?u)[^-\w.]', '', str(name).strip().replace(' ', '_'))

def save_student_json(student_data):
    """Saves individual student data to json/School_Name/roll_no.json"""
    base_dir = "json"
    safe_school_name = clean_filename(student_data['school'])
    folder_path = os.path.join(base_dir, safe_school_name)
    
    # Create the directories if they don't exist
    os.makedirs(folder_path, exist_ok=True)
    
    file_path = os.path.join(folder_path, f"{student_data['roll_no']}.json")
    
    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(student_data, f, indent=4, ensure_ascii=False)

def fetch_single_student(roll, roll_code, max_retries=5):
    """Fetches a single student's complete scorecard with progressive automatic retries."""
    form_url = "https://jacresults.com/enter-class-x-2026-student-details"
    formatted_roll = str(roll).zfill(4)
    
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8",
        "Origin": "https://jacresults.com",
        "Referer": "https://jacresults.com/enter-class-x-2026-student-details"
    }
    
    for attempt in range(max_retries):
        with requests.Session() as session:
            session.headers.update(headers)
            
            try:
                # 1. Grab fresh tokens
                r = session.get(form_url, timeout=15)
                soup = BeautifulSoup(r.text, "html.parser")
                
                viewstate_tag = soup.find("input", {"id": "__VIEWSTATE"})
                if not viewstate_tag:
                    delay = 2 + (attempt * 2) 
                    time.sleep(delay)
                    continue

                viewstate = viewstate_tag["value"]
                viewstategen = soup.find("input", {"id": "__VIEWSTATEGENERATOR"})["value"]
                eventvalidation = soup.find("input", {"id": "__EVENTVALIDATION"})["value"]

                # 2. Submit data
                form_data = {
                    "__VIEWSTATE": viewstate,
                    "__VIEWSTATEGENERATOR": viewstategen,
                    "__EVENTVALIDATION": eventvalidation,
                    "ctl00$ContentPlaceHolder1$txt_code": roll_code,
                    "ctl00$ContentPlaceHolder1$txt_no": formatted_roll,
                    "ctl00$ContentPlaceHolder1$btn_submit": "Submit"
                }
                
                post_response = session.post(form_url, data=form_data, timeout=15)
                
                if "No record found" in post_response.text or "alert('No record" in post_response.text:
                    with print_lock:
                        print(f"❌ Roll {formatted_roll} - Not Found (Empty)")
                    return {"status": "EMPTY", "roll": roll}

                soup_post = BeautifulSoup(post_response.text, "html.parser")
                name_tag = soup_post.find("span", id="ContentPlaceHolder1_lblstudentname")
                
                if name_tag:
                    name = name_tag.text.strip()
                    father = soup_post.find("span", id="ContentPlaceHolder1_lblfather").text.strip()
                    mother = soup_post.find("span", id="ContentPlaceHolder1_lblmother").text.strip()
                    school = soup_post.find("span", id="ContentPlaceHolder1_lblschoolname").text.strip()
                    total = soup_post.find("span", id="ContentPlaceHolder1_lbltotalobt").text.strip()
                    percent = soup_post.find("span", id="ContentPlaceHolder1_lblpercentage").text.strip()
                    result_div = soup_post.find("span", id="ContentPlaceHolder1_lbldivision").text.strip()

                    subjects = []
                    subject_ids = ['lang1', 'lang2', 'compl1', 'compl2', 'compl3', 'compl4']
                    
                    for sub_id in subject_ids:
                        sub_name_tag = soup_post.find("span", id=f"ContentPlaceHolder1_lbl{sub_id}")
                        if sub_name_tag:
                            def get_text(suffix):
                                elem = soup_post.find("span", id=f"ContentPlaceHolder1_lbl{sub_id}{suffix}")
                                return elem.text.strip() if elem else "-"

                            subjects.append({
                                "name": sub_name_tag.text.strip(),
                                "th": get_text("th"),
                                "pr": get_text("pr"),
                                "total": get_text("total"),
                                "grade": get_text("grade"),
                                "remarks": get_text("remarks")
                            })

                    with print_lock:
                        print(f"✅ Fetched Roll {formatted_roll} - {name}")
                        
                    return {
                        "status": "SUCCESS",
                        "data": {
                            "roll_code": roll_code, "roll_no": formatted_roll, "name": name,
                            "father": father, "mother": mother, "school": school,
                            "total": total, "percent": percent, "result": result_div, "subjects": subjects
                        }
                    }
                else:
                    delay = 2 + (attempt * 2)
                    time.sleep(delay)  
                    continue

            except requests.exceptions.RequestException:
                delay = 2 + (attempt * 2)
                time.sleep(delay)
                continue
            
    with print_lock:
        print(f"⚠️ Exhausted {max_retries} retries for Roll {formatted_roll}. Server rejected the request.")
        
    return {"status": "ERROR", "roll": roll}

